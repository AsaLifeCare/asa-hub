#!/usr/bin/env python3
"""
Write app/other_lanes.json from server/snapshot_service.py: the relay's tables its /hub-lanes doors answer from that
asa-hub-app's own copies of those doors (app/other_lanes.py) read as the relay reads them.

  backends        BACKEND_APPS: Settings › Back-end per app's rows (id, label, reads, writes, final), in its order
  backend_gas     BACKEND_GAS_REFUSED, BACKEND_CHOICES
  tech_statuses   _TECH_STATUSES (the Technology status dropdown's words)

The relay's constants are read as tools/emit-front-door-routes.py reads them: nothing is imported from the relay.

    python3 tools/emit-other-lanes.py            # writes the file
    python3 tools/emit-other-lanes.py --check    # exit 1 when the file differs from the relay
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "other_lanes.json"


def _routes_emitter() -> Any:
    spec = importlib.util.spec_from_file_location("emit_front_door_routes", ROOT / "tools" / "emit-front-door-routes.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def build(src: str) -> dict[str, Any]:
    emitter = _routes_emitter()
    _tree, ns = emitter.relay_namespace(src)
    apps = ns["BACKEND_APPS"]
    rows = [{"id": app_id, "label": str(spec["label"]), "reads": sorted(spec["reads"]),
             "writes": sorted(spec.get("writes", ())),
             "final": sorted(a for a in spec.get("final", ()) if a in spec.get("writes", ()))}
            for app_id, spec in apps.items()]
    return {
        "_": "Generated by tools/emit-other-lanes.py from server/snapshot_service.py; never edited by hand.",
        "backends": rows,
        "backend_gas": {"refused": dict(ns["BACKEND_GAS_REFUSED"]), "choices": list(ns["BACKEND_CHOICES"])},
        "tech_statuses": list(ns["_TECH_STATUSES"]),
    }


def dump(tables: dict[str, Any]) -> str:
    return json.dumps(tables, indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    emitter = _routes_emitter()
    text = dump(build(emitter.RELAY.read_text(encoding="utf-8")))
    if "--check" in argv:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("app/other_lanes.json " + ("matches the relay" if same else "DIFFERS from the relay"))
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(json.loads(text)['backends'])} back-end rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
