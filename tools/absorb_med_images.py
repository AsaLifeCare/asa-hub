#!/usr/bin/env python3
"""
Absorb the old platform's medication photos into the Hub's own bundle.

THE RULE: bring the images across, but WITHOUT the dependency — that service
is being discontinued. the old platform serves 165 drug photos from its own
disk (var/drive_cache/.../eMar Images/) through its own endpoints; every
med_pictures URL in the eMAR rows points at infrastructure that is going
away. So the files come HERE: public/med-images/ ships inside the SPA
bundle (1.7 MB total), each file under a stable slug, with a manifest
mapping normalized drug keys to paths. The screen resolves a photo from
the manifest first and only falls back to the old URL while it still
answers.

Re-runnable: overwrites slugs deterministically, rewrites the manifest.

    python3 tools/absorb_med_images.py
"""
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

SRC = Path(os.environ.get("HUB_MED_IMAGES_SRC") or "/dev/null/none")  # the folder the images were once absorbed from
DST = Path("/opt/docker/asa-hub/public/med-images")
# the manifest lives in src/ as a generated TS module (Vite forbids module
# imports out of public/, and the tsconfig has no resolveJsonModule); the
# images stay in public/ and are served as static files next to the app
MANIFEST = Path("/opt/docker/asa-hub/src/lib/med-images.manifest.ts")


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main() -> None:
    DST.mkdir(parents=True, exist_ok=True)
    entries: dict[str, str] = {}
    files = sorted(p for p in SRC.iterdir() if p.is_file())
    for p in files:
        stem, ext = p.stem, p.suffix.lower()
        if ext not in (".png", ".jpg", ".jpeg", ".webp", ".gif"):
            print(f"skipped (not an image): {p.name}")
            continue
        s = slug(stem)
        out = DST / f"{s}{ext}"
        shutil.copy2(p, out)
        # full-name key, and the first token as a fallback key the way the
        # the old platform matched (first filename token) — first writer wins on clashes
        entries.setdefault(s, out.name)
        first = slug(stem.split()[0]) if stem.split() else ""
        if first:
            entries.setdefault(first, out.name)
    body = json.dumps(dict(sorted(entries.items())), indent=1)
    MANIFEST.write_text(
        "// GENERATED by tools/absorb_med_images.py — do not edit by hand.\n"
        "// Normalized drug key -> filename under public/med-images/.\n"
        f"const MED_IMAGE_FILES: Record<string, string> = {body}\n"
        "export default MED_IMAGE_FILES\n")
    n_files = len(list(DST.glob("*.*"))) - 1
    print(f"{n_files} image(s) in {DST}")
    print(f"{len(entries)} manifest key(s) in {MANIFEST}")


if __name__ == "__main__":
    main()
